import postgres from 'postgres';
import { makeHandler } from '../out/handler.js';
import { PG_TYPES } from '../out/db.js';
const sql = postgres({ host: '127.0.0.1', username: 'postgres', database: 'lc26a', max: 4, types: PG_TYPES, onnotice: () => {} });
let pass = 0, fail = 0; const ok = (c, m) => { if (c) { pass++; console.log('  ok  ' + m); } else { fail++; console.log('  FAIL ' + m); } };
const mk = (extra) => makeHandler(sql, Object.assign({ PID_SALT: 'salt-salt-salt-salt', ADMIN_TOKEN: 'admin-token-admin-token' }, extra || {}));
const call = (h) => async (action, body) => { const r = await h(new Request('https://x.test/', { method: 'POST', headers: { Origin: 'https://lanckrietchess-app.vercel.app', 'content-type': 'application/json' }, body: JSON.stringify(Object.assign({ action }, body)) })); return Object.assign({ status: r.status }, await r.json()); };
await sql.unsafe('truncate arena.players, arena.quota, arena.token_ledger, arena.token_bonus, arena.token_spend');
const c = call(mk());          // production defaults: TOKENS_FREE 1, boost 3 for 7 days
console.log('A. a new free player gets 3 tokens a day');
let r = await c('token_state', { device: 'week1-device-aaaa-1' });
ok(r.ok && r.state.tier === 'free' && r.state.limit === 3 && r.state.left === 3, 'limit 3, left 3 on day one');
ok(r.state.week1 === true && r.state.week1Ends > Date.now() + 6 * 864e5 && r.state.week1Ends < Date.now() + 7.01 * 864e5, 'the state says it is the habit week and when it ends (about 7 days away)');
const spends = [];
for (let i = 1; i <= 4; i++) spends.push(await c('token_spend', { device: 'week1-device-aaaa-1', kind: 'coach', ref: 'wk-' + i }));
ok(spends.slice(0, 3).every((x) => x.ok && x.charged), 'three coaching actions go through');
ok(spends[2].state.left === 0 && spends[2].state.used === 3, 'then the day is spent (3 of 3)');
ok(spends[3].status === 403 && spends[3].reason === 'token_limit', 'the fourth is refused with token_limit');
console.log('B. after the first week the free limit is 1 again');
const pid = (await c('hello', { device: 'week1-device-aaaa-1' })).pid;
await sql.unsafe('update arena.players set created = $1 where pid = $2', [Date.now() - 8 * 864e5, pid]);
await sql.unsafe('truncate arena.token_ledger');
r = await c('token_state', { device: 'week1-device-aaaa-1' });
ok(r.state.limit === 1 && r.state.left === 1 && r.state.week1 === false, 'day 8: limit 1, left 1, no habit week');
await sql.unsafe('update arena.players set created = $1 where pid = $2', [Date.now() - 6.9 * 864e5, pid]);
r = await c('token_state', { device: 'week1-device-aaaa-1' });
ok(r.state.limit === 3 && r.state.week1 === true, 'day 7 (6.9 days old): still 3');
console.log('C. switches');
const off = call(mk({ TOKENS_FREE_BOOST_DAYS: '0' }));
r = await off('token_state', { device: 'fresh-device-bbbb-2' });
ok(r.state.limit === 1 && r.state.week1 === false, 'TOKENS_FREE_BOOST_DAYS=0 switches the habit week off');
const five = call(mk({ TOKENS_FREE_BOOST: '5', TOKENS_FREE_BOOST_DAYS: '3' }));
r = await five('token_state', { device: 'fresh-device-cccc-3' });
ok(r.state.limit === 5 && r.state.week1Ends < Date.now() + 3.01 * 864e5, 'boost size and length are settings (5 a day for 3 days)');
const small = call(mk({ TOKENS_FREE: '4' }));
r = await small('token_state', { device: 'fresh-device-dddd-4' });
ok(r.state.limit === 4, 'if the normal free limit is already higher than the boost, nobody gets less');
console.log('D. paid tiers are not touched');
const adm = await c('token_state', { device: 'admin-device-eeee-5', secret: 'admin-token-admin-token' });
ok(adm.state.tier === 'vip' && adm.state.week1 === false, 'admin / VIP: no habit-week flag');
console.log('E. the Carousel voice job uses the same limit');
r = await c('carousel_voice', { device: 'fresh-device-ffff-6', dry: true, texts: ['Hello there this is a test.'] });
ok(r.ok && r.state.limit === 3, 'voice price check shows the 3-token habit week limit');
console.log(`\n${pass} passed, ${fail} failed`); await sql.end();
