import { boot } from './mountStudio.mjs'; import { sleep } from './rig.mjs';
let pass=0, fail=0; const ok=(c,m)=>{ if(c){pass++;console.log('  ok  ',m)}else{fail++;console.log('  FAIL',m)} };
const { rig, d } = await boot({ w: 1440, h: 1000 });
const p = d.page;
const ev = (code) => p.evaluate(`(()=>{const R=document.getElementById('harness').shadowRoot;const q=s=>R.querySelector(s);const qa=s=>[...R.querySelectorAll(s)];${code}})()`);
await sleep(700);
await ev(`q('.lc31-fmt[data-fmt=long]').click();return 1`); await sleep(500);
// arrange mode, drag the camera layer with the real mouse
await ev(`q('#btn-arrange').click();return 1`); await sleep(300);
const box = await ev(`const e=q('.layer[data-layer=camera]');const r=e.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}`);
const before = await p.evaluate(()=>{const c=LanckrietStudio.layout().layers.camera;return {x:c.x,y:c.y,w:c.w,h:c.h}});
await p.mouse.move(box.x+box.w/2, box.y+box.h/2); await p.mouse.down(); 
await p.mouse.move(box.x+box.w/2-90, box.y+box.h/2+40, {steps:8}); await p.mouse.move(box.x+box.w/2-180, box.y+box.h/2+70, {steps:8}); await p.mouse.up(); await sleep(200);
const after = await p.evaluate(()=>{const c=LanckrietStudio.layout().layers.camera;return {x:c.x,y:c.y,w:c.w,h:c.h}});
console.log('    camera moved',JSON.stringify(before),'->',JSON.stringify(after));
ok(Math.abs(after.x-before.x)>.05 && after.w===before.w, 'dragging the camera layer moves it with the mouse');
ok(after.x>=0&&after.y>=0&&after.x+after.w<=1.0001&&after.y+after.h<=1.0001,'it stays inside the frame');
// resize with the corner handle keeps the ratio of the chosen shape
await ev(`const s=q('#lc31-look');s.value='wide';s.dispatchEvent(new Event('change'));return 1`); await sleep(200);
const h0 = await ev(`const e=q('.layer[data-layer=camera] .h.se');const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}`);
const w0 = await p.evaluate(()=>{const c=LanckrietStudio.layout().layers.camera;return {w:c.w,h:c.h}});
await p.mouse.move(h0.x,h0.y); await p.mouse.down(); await p.mouse.move(h0.x-40,h0.y-30,{steps:6}); await p.mouse.up(); await sleep(200);
const w1 = await p.evaluate(()=>{const c=LanckrietStudio.layout().layers.camera;return {w:c.w,h:c.h}});
const a=16/9; const r0=w0.w*a/w0.h, r1=w1.w*a/w1.h;
console.log('    resize ratio',r0.toFixed(3),'->',r1.toFixed(3),'width',w0.w.toFixed(3),'->',w1.w.toFixed(3));
ok(Math.abs(w1.w-w0.w)>.005,'corner handle resizes the camera');
ok(Math.abs(r1-16/9)<.03,'resize keeps the 16:9 ratio of the chosen shape');
// panel drag via header
const ph = await ev(`const e=q('section[data-id=library] .p-head');const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}`);
const pb = await p.evaluate(()=>{const l=LanckrietStudio.layout().panels.library;return {x:l.x,y:l.y}});
await p.mouse.move(ph.x,ph.y); await p.mouse.down(); await p.mouse.move(ph.x-120,ph.y+30,{steps:8}); await p.mouse.up(); await sleep(250);
const pa = await p.evaluate(()=>{const l=LanckrietStudio.layout().panels.library;return {x:l.x,y:l.y}});
console.log('    panel moved',JSON.stringify(pb),'->',JSON.stringify(pa));
ok(pa.x<pb.x-.03,'dragging a panel header moves the panel');
// persistence across remount
const saved = await p.evaluate(()=>JSON.stringify(LanckrietStudio.layout().layers.camera));
await p.evaluate(()=>{LanckrietStudio.unmount();const h=document.getElementById('harness');LanckrietStudio.mount(h,{isLocked:()=>false,isAdmin:()=>true,tier:()=>'free',isCreator:()=>true,upgrade(){}},{embedded:true})}); await sleep(900);
const re = await p.evaluate(()=>JSON.stringify(LanckrietStudio.layout().layers.camera));
ok(saved===re,'layout survives closing and reopening the Studio');
ok(await ev(`return !q('.lc31-fmts')`),'format picker does not nag again once a format is chosen');
await d.shot('t10-desktop');
await rig.close();
const B = await boot({ w: 390, h: 844 }); const p2 = B.d.page;
const ev2 = (code) => p2.evaluate(`(()=>{const R=document.getElementById('harness').shadowRoot;const q=s=>R.querySelector(s);const qa=s=>[...R.querySelectorAll(s)];${code}})()`);
await sleep(900);
ok(await ev2(`return !!q('.lc31-fmts')`),'phone: picker opens');
const mo = await ev2(`const m=q('.lc31-modal');const b=m.getBoundingClientRect();return {l:b.left,r:b.right,w:innerWidth}`);
ok(mo.l>=0&&mo.r<=mo.w+1,'phone: format picker fits the screen');
await B.d.shot('t10-phone-picker');
await ev2(`q('.lc31-fmt[data-fmt=short]').click();return 1`); await sleep(700);
const over = await ev2(`const r=q('#lc31-row');const b=r.getBoundingClientRect();return {rowW:b.width,scrollW:r.scrollWidth,vw:innerWidth}`);
console.log('    phone',JSON.stringify(over));
ok(over.scrollW<=over.rowW+1,'phone: stage button row does not overflow');
await B.d.shot('t10-phone');
const errs2=[...d.errors,...B.d.errors].filter(e=>!/404|fetching the script|Failed to load/.test(e));
console.log('errors', errs2.slice(0,6));
ok(errs2.length===0,'no page errors');
console.log(`\n${pass} passed, ${fail} failed`);
await B.rig.close();
